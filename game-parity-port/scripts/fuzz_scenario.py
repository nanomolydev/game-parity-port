#!/usr/bin/env python3
"""Randomized scenario generator: new input and data on every run, reproducible by seed.

    fuzz_scenario.py BASE.json ACTIONS.json OUT.json [seed]

BASE.json is an ordinary scenario (spawn list, level setup, ...). Its "input", "frames", "seed" and
the positions of spawned objects matched in ACTIONS.json are replaced. Prints the seed used.

ACTIONS.json (all keys optional):
{
  "frames": [300, 600],                 # random length range
  "start": [40, 70],                    # first input frame range (after the level is ready)
  "segment": [5, 60],                   # length of one input segment
  "gap": [0, 15],                       # pause between segments
  "always": [{"from": 0, "to": 99999, "mousePosition": [960, 540]}],
  "moves": ["<Keyboard>/w", "<Keyboard>/a", "<Keyboard>/s", "<Keyboard>/d"],
  "move_count": [0, 1, 1, 2],           # how many move keys at once (picked from this list)
  "modifiers": [["<Keyboard>/leftShift", 0.25], ["<Keyboard>/leftCtrl", 0.15]],   # [key, chance]
  "mouse": {"chance": 0.6, "dx": [-12, 12], "dy": [-6, 6]},
  "taps": [["<Keyboard>/space", 0.3], ["<Keyboard>/q", 0.05]],                      # [key, chance]
  "holds": [["<Mouse>/leftButton", 0.2]],                                           # [key, chance] over a whole segment
  "place": [{"match": "Vase", "x": [-1.8, 1.8], "y": 0.3, "z": [-5.5, -1.5]}],     # spawn entries whose comment/prefab contains match
  "min_distance": 1.0                   # keep placed objects at least this far apart (x/z)
}
"""
import json, random, sys, time


def rint(rng, r): return rng.randint(r[0], r[1]) if isinstance(r, list) else r
def rflt(rng, r): return round(rng.uniform(r[0], r[1]), 3) if isinstance(r, list) else r


def main():
    base, actions_path, out = sys.argv[1], sys.argv[2], sys.argv[3]
    seed = int(sys.argv[4]) if len(sys.argv) > 4 else int(time.time() * 1000) % 2**31
    rng = random.Random(seed)
    sc = json.load(open(base))
    A = json.load(open(actions_path))
    frames = rint(rng, A.get("frames", [300, 600]))
    sc["name"] = f"fuzz_{seed}"
    sc["frames"] = frames
    sc["seed"] = rng.randint(1, 2**31 - 1)

    placed = []
    for rule in A.get("place", []):
        for s in sc.get("spawn", []):
            if rule["match"] not in (s.get("comment", "") + s.get("prefab", "")):
                continue
            for _ in range(50):
                p = [rflt(rng, rule.get("x", 0)), rflt(rng, rule.get("y", 0)), rflt(rng, rule.get("z", 0))]
                if all(abs(p[0] - q[0]) + abs(p[2] - q[2]) >= A.get("min_distance", 0) for q in placed):
                    break
            s["pos"] = p
            placed.append(p)

    inp = list(A.get("always", []))
    moves = A.get("moves", [])
    f = rint(rng, A.get("start", [40, 70]))
    while f < frames - 10:
        n = rint(rng, A.get("segment", [5, 60]))
        hold = rng.sample(moves, min(len(moves), rng.choice(A.get("move_count", [0, 1, 1, 2])))) if moves else []
        for key, chance in A.get("modifiers", []):
            if rng.random() < chance:
                hold.append(key)
                break
        for key, chance in A.get("holds", []):
            if rng.random() < chance:
                hold.append(key)
        if hold:
            inp.append({"from": f, "to": f + n, "hold": hold})
        m = A.get("mouse")
        if m and rng.random() < m.get("chance", 0.5):
            inp.append({"from": f, "to": f + rng.randint(1, n), "mouseDelta": [rflt(rng, m.get("dx", [-10, 10])), rflt(rng, m.get("dy", [-5, 5]))]})
        for key, chance in A.get("taps", []):
            if rng.random() < chance:
                inp.append({"at": f + rng.randint(0, n), "tap": key})
        f += n + rint(rng, A.get("gap", [0, 15]))
    sc["input"] = inp
    sc["comment"] = f"generated by fuzz_scenario.py from {base} with seed {seed}"
    json.dump(sc, open(out, "w"), indent=1)
    print(seed)


if __name__ == "__main__":
    main()
